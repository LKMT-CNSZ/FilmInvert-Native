"""RGB 输出变换和自生成 matrix/TRC ICC；不分发第三方 ICC 文件。

参考：Adobe RGB (1998) encoding specification；ICC ROMM RGB registry。
兼容管线采用 sRGB；可选宽色域管线采用 ProPhoto，直接转换到目标输出编码。
"""
from functools import lru_cache
import hashlib
import struct
import numpy as np
from PIL import ImageCms

SPACES = ('srgb', 'adobe_rgb', 'prophoto')
NAMES = {'srgb':'sRGB', 'adobe_rgb':'Adobe RGB (1998)', 'prophoto':'ProPhoto RGB'}
D50 = np.array([.9642, 1., .8249], np.float64)
D65 = np.array([.95047, 1., 1.08883], np.float64)
BRADFORD = np.array([[.8951,.2664,-.1614],[-.7502,1.7135,.0367],[.0389,-.0685,1.0296]])
ADAPT = np.linalg.inv(BRADFORD) @ np.diag((BRADFORD@D50)/(BRADFORD@D65)) @ BRADFORD

def matrix(primaries, white):
    xy = np.array(primaries, np.float64)
    xyz = np.stack((xy[:,0]/xy[:,1], np.ones(3), (1-xy[:,0]-xy[:,1])/xy[:,1]))
    return xyz * np.linalg.solve(xyz, white)[None,:]

MATRICES = {
    'srgb': matrix(((.64,.33),(.30,.60),(.15,.06)), D65),
    'adobe_rgb': matrix(((.64,.33),(.21,.71),(.15,.06)), D65),
    'prophoto': matrix(((.7347,.2653),(.1596,.8404),(.0366,.0001)), D50),
}

def decode(rgb, space):
    x = np.clip(np.asarray(rgb, np.float32), 0, 1)
    if space == 'srgb':
        return np.where(x <= .04045, x/12.92, ((x+.055)/1.055)**2.4).astype(np.float32)
    if space == 'adobe_rgb':
        return (x**np.float32(563/256)).astype(np.float32)
    if space == 'prophoto':
        return np.where(x < .03125, x/16, x**np.float32(1.8)).astype(np.float32)
    raise ValueError('未知输出色彩空间')

def encode(lin, space):
    x = np.clip(np.asarray(lin, np.float32), 0, 1)
    if space == 'srgb':
        return np.where(x <= .0031308, x*12.92, 1.055*x**np.float32(1/2.4)-.055).astype(np.float32)
    if space == 'adobe_rgb':
        return (x**np.float32(256/563)).astype(np.float32)
    if space == 'prophoto':
        return np.where(x < 1/512, x*16, x**np.float32(1/1.8)).astype(np.float32)
    raise ValueError('未知输出色彩空间')

def target_linear(rgb, target='srgb', source='srgb'):
    """Exact export conversion before target encoding clips; source decode clips too."""
    if target not in SPACES or source not in SPACES:raise ValueError('未知输出色彩空间')
    adaptation = np.eye(3)
    if (source == 'prophoto') != (target == 'prophoto'):
        adaptation = ADAPT if target == 'prophoto' else np.linalg.inv(ADAPT)
    transform = (np.linalg.inv(MATRICES[target]) @ adaptation @ MATRICES[source]).astype(np.float32)
    return decode(rgb, source) if target==source else decode(rgb, source) @ transform.T


def output_diagnostics(rgb, target='srgb', source='srgb'):
    # 1e-6 excludes float32 matrix roundoff at neutral gamut boundaries.
    lin=target_linear(rgb,target,source)
    low=np.any(lin < -1e-6,axis=2);high=np.any(lin > 1+1e-6,axis=2)
    codes=np.rint(np.clip(convert(rgb,target,source),0,1)*65535)
    sample=codes[::max(1,len(codes)//640),::max(1,codes.shape[1]//640)]
    hist=[np.bincount((sample[...,c]/257).astype(np.uint8).ravel(),minlength=256) for c in range(3)]
    return dict(low=low,high=high,fraction=float(np.mean(low|high)),
                endpoints=float(np.mean(np.any((codes==0)|(codes==65535),axis=2))),hist=hist)


def convert(rgb, target='srgb', source='srgb'):
    if target not in SPACES or source not in SPACES:
        raise ValueError('未知输出色彩空间')
    if target == source:
        return rgb
    return encode(target_linear(rgb,target,source),target)


def _fixed(values):
    a = np.rint(np.array(values)*65536).astype('>i4')
    return a.tobytes()

def _xyz(values):
    return b'XYZ '+b'\0'*4+_fixed(values)

def _mluc(text):
    raw = text.encode('utf-16-be')
    return b'mluc'+b'\0'*4+struct.pack('>II',1,12)+b'enUS'+struct.pack('>II',len(raw),28)+raw

@lru_cache(maxsize=3)
def icc_profile(space='srgb'):
    if space == 'srgb':
        return ImageCms.ImageCmsProfile(ImageCms.createProfile('sRGB')).tobytes()
    if space not in SPACES:
        raise ValueError('未知输出色彩空间')
    colorants = MATRICES[space]
    if space != 'prophoto':
        colorants = ADAPT @ colorants
    # 显式 sampled TRC，包含 ProPhoto 的线性趾部，编码与像素转换一致。
    codes = np.linspace(0,1,16384,dtype=np.float32)
    trc = b'curv'+b'\0'*4+struct.pack('>I',len(codes))+(decode(codes,space)*65535+.5).astype('>u2').tobytes()
    name = ('FilmInvert - Adobe RGB (1998) compatible' if space == 'adobe_rgb'
            else 'FilmInvert ProPhoto RGB (ROMM RGB)')
    tags = {b'desc':_mluc(name), b'cprt':_mluc('Generated by film-invert; no third-party ICC profile bundled.'),
            b'wtpt':_xyz(D50), b'rXYZ':_xyz(colorants[:,0]), b'gXYZ':_xyz(colorants[:,1]),
            b'bXYZ':_xyz(colorants[:,2]), b'rTRC':trc,b'gTRC':trc,b'bTRC':trc}
    if space == 'adobe_rgb':
        tags[b'chad'] = b'sf32'+b'\0'*4+_fixed(ADAPT)
    header = bytearray(128)
    header[4:8] = b'pyFI'
    struct.pack_into('>I',header,8,0x04300000)
    header[12:24] = b'mntrRGB XYZ '
    struct.pack_into('>6H',header,24,2026,10,22,0,0,0)
    header[36:44] = b'acspMSFT'
    struct.pack_into('>I',header,64,1)  # relative colorimetric
    header[68:80] = _fixed(D50)
    header[80:84] = b'pyFI'
    table, payload = bytearray(), bytearray()
    start = 128+4+12*len(tags)
    for key, value in tags.items():
        table += key+struct.pack('>II', start+len(payload),len(value))
        payload += value+b'\0'*((-len(value)) % 4)
    result = header+struct.pack('>I',len(tags))+table+payload
    struct.pack_into('>I',result,0,len(result))
    for_digest = bytearray(result)
    for_digest[44:48] = b'\0'*4
    for_digest[64:68] = b'\0'*4
    result[84:100] = hashlib.md5(for_digest).digest()
    return bytes(result)


def export_strips(rgb,target,source,statistics,rows):
    """Convert and count export diagnostics with strip-sized scratch, no full masks."""
    count=outside=endpoints=0
    for y in range(0,len(rgb),rows):
        block=rgb[y:y+rows];lin=target_linear(block,target,source)
        outside+=int(np.count_nonzero(np.any((lin < -1e-6)|(lin > 1+1e-6),axis=2)))
        encoded=convert(block,target,source)
        codes=np.rint(np.clip(encoded,0,1)*65535)
        endpoints+=int(np.count_nonzero(np.any((codes==0)|(codes==65535),axis=2)))
        count+=block.shape[0]*block.shape[1]
        yield y,encoded
    statistics.update(fraction=outside/count,endpoints=endpoints/count)
